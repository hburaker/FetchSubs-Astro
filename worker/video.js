// GET /api/video?id=<videoId>
// Returns the video details and its caption tracks.
//
// 1. Direct: asks YouTube itself. Tracks then carry a signed `url` that the browser downloads directly.
// 2. Legacy fallback: if YouTube refuses the Cloudflare IP (bot check) or the call fails, asks the old FetchSubs
//    server (LEGACY_API_ORIGIN). Those tracks have `url: null`; the browser downloads them via /api/subtitle.
import { BLOCKED_MESSAGE, VIDEO_ID, blockedIds, getPlayer, json, legacyOrigin, legacyPost } from './youtube.js';

const UNREACHABLE = 'Could not reach YouTube. Please try again in a moment.';

export async function handleVideo(request, env, ctx) {
  const id = new URL(request.url).searchParams.get('id') || '';
  if (!VIDEO_ID.test(id)) return json({ success: false, message: 'Invalid YouTube video ID.' }, 400);
  if (blockedIds(env).has(id)) return json({ success: false, message: BLOCKED_MESSAGE });

  // Signed caption URLs stay valid for several hours, so a short edge cache is safe and spares YouTube calls.
  const cache = caches.default;
  const cacheKey = new Request(`https://fetchsubs-cache/api/video?id=${id}`);
  const cached = await cache.match(cacheKey);
  if (cached) return cached;

  let result = await fromYouTube(id);
  if (!result.data && legacyOrigin(env)) result = await fromLegacy(env, id, result.message);
  if (!result.data) return json({ success: false, message: result.message || UNREACHABLE }, result.status || 200);

  const response = json({ success: true, data: result.data }, 200, { 'Cache-Control': 'public, max-age=1800' });
  ctx.waitUntil(cache.put(cacheKey, response.clone()));
  return response;
}

async function fromYouTube(id) {
  let player;
  try {
    player = await getPlayer(id);
  } catch {
    return { message: UNREACHABLE, status: 502 };
  }

  const status = player.playabilityStatus?.status;
  const details = player.videoDetails;
  if (!details || (status && status !== 'OK' && !player.captions)) {
    const reason = player.playabilityStatus?.reason || 'This video is unavailable.';
    return { message: `Video error: ${reason}` };
  }

  const thumbs = details.thumbnail?.thumbnails || [];
  const best = thumbs.reduce((a, b) => ((b.width || 0) * (b.height || 0) > (a?.width || 0) * (a?.height || 0) ? b : a), null);
  const tracks = (player.captions?.playerCaptionsTracklistRenderer?.captionTracks || []).map((t) => ({
    language: t.name?.simpleText || t.name?.runs?.map((r) => r.text).join('') || t.languageCode,
    languageCode: t.languageCode,
    isAutoGenerated: t.kind === 'asr',
    url: t.baseUrl,
  }));

  return {
    data: {
      videoId: id,
      title: details.title || '',
      author: details.author || '',
      lengthSeconds: Number(details.lengthSeconds) || 0,
      thumbnailUrl: best?.url || `https://i.ytimg.com/vi/${id}/hqdefault.jpg`,
      videoUrl: `https://www.youtube.com/watch?v=${id}`,
      description: details.shortDescription || '',
      tracks,
    },
  };
}

async function fromLegacy(env, id, directMessage) {
  let body;
  try {
    body = await legacyPost(env, '/fetch-info', { url: `https://www.youtube.com/watch?v=${id}` });
  } catch {
    return { message: directMessage || UNREACHABLE, status: 502 };
  }
  const d = body?.data;
  if (!body?.success || !d) return { message: body?.message || directMessage || UNREACHABLE };

  // The legacy server sends PascalCase fields and the duration as "hh:mm:ss".
  const lengthSeconds = String(d.Duration || '0')
    .split(':')
    .reduce((total, part) => total * 60 + (Number(part) || 0), 0);
  return {
    data: {
      videoId: d.VideoId || id,
      title: d.Title || '',
      author: d.Author || '',
      lengthSeconds,
      thumbnailUrl: d.ThumbnailUrl || `https://i.ytimg.com/vi/${id}/hqdefault.jpg`,
      videoUrl: d.VideoUrl || `https://www.youtube.com/watch?v=${id}`,
      description: d.Description || '',
      tracks: (d.Subtitles || []).map((t) => ({
        language: t.Language || t.LanguageCode,
        languageCode: t.LanguageCode,
        isAutoGenerated: !!t.IsAutoGenerated,
        url: null,
      })),
    },
  };
}
