// Browser side of the subtitle tool.
//
// 1. /api/video (a Cloudflare Pages Function) asks YouTube for the video details and caption track list.
//    That single call cannot be made from the browser because YouTube's player API does not allow CORS.
// 2. The caption file itself is downloaded straight from YouTube by the browser (the signed timedtext URL
//    is CORS-enabled and not tied to an IP), then converted to SRT / VTT / TXT here. No caption data passes
//    through our function unless the direct download fails.

import { buildFileName, captionsToSrt, captionsToTxt, captionsToVtt, parseTimedText, type Caption } from './captions';
import { extractVideoId } from './youtube-url';

interface Track {
  language: string;
  languageCode: string;
  isAutoGenerated: boolean;
  url: string;
}

interface VideoData {
  videoId: string;
  title: string;
  author: string;
  lengthSeconds: number;
  thumbnailUrl: string;
  videoUrl: string;
  description: string;
  tracks: Track[];
}

type Format = 'srt' | 'vtt' | 'txt' | 'raw';

function formatDuration(totalSeconds: number): string {
  const s = Math.max(0, Math.floor(totalSeconds || 0));
  const pad = (n: number) => String(n).padStart(2, '0');
  return `${pad(Math.floor(s / 3600))}:${pad(Math.floor((s % 3600) / 60))}:${pad(s % 60)}`;
}

function escapeHtml(value: unknown): string {
  return String(value ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]!);
}

function track(event: string, params: Record<string, unknown>) {
  const gtag = (window as unknown as { gtag?: (...args: unknown[]) => void }).gtag;
  if (gtag) gtag('event', event, params);
}

/** Downloads a caption track: directly from YouTube first, through our function as a fallback. */
async function loadCaptions(t: Track): Promise<Caption[]> {
  const direct = t.url.replace(/&fmt=[^&]*/g, '') + '&fmt=srv3';
  try {
    const res = await fetch(direct, { credentials: 'omit' });
    if (res.ok) {
      const captions = parseTimedText(await res.text());
      if (captions.length) return captions;
    }
  } catch {
    /* fall through to the proxy */
  }
  const res = await fetch('/api/caption?url=' + encodeURIComponent(direct));
  if (!res.ok) throw new Error('caption proxy ' + res.status);
  return parseTimedText(await res.text());
}

export function initTool() {
  const tool = document.getElementById('fetchsubs-tool');
  if (!tool) return;
  const labels = {
    auto: tool.dataset.labelAuto ?? '',
    official: tool.dataset.labelOfficial ?? '',
    networkError: tool.dataset.labelNetworkError ?? '',
    downloadError: tool.dataset.labelDownloadError ?? '',
    invalidUrl: tool.dataset.labelInvalidUrl ?? '',
    noTracks: tool.dataset.labelNoTracks ?? '',
  };

  const $ = <T extends HTMLElement>(id: string) => document.getElementById(id) as T;
  const input = $<HTMLInputElement>('videoUrl');
  const fetchBtn = $<HTMLButtonElement>('fetchBtn');
  const loading = $('loading-container');
  const result = $('result-container');
  const errorBox = $('error-message');
  const grid = $('subs-grid');
  let errorTimer: number | undefined;

  function showError(message: string, autoHide = false) {
    window.clearTimeout(errorTimer);
    errorBox.textContent = message;
    errorBox.style.display = 'block';
    if (autoHide) {
      errorTimer = window.setTimeout(() => (errorBox.style.display = 'none'), 5000);
      window.scrollTo({ top: 0, behavior: 'smooth' });
    }
  }

  async function fetchVideo() {
    const raw = input.value.trim();
    if (!raw) return;
    errorBox.style.display = 'none';
    result.style.display = 'none';

    const videoId = extractVideoId(raw);
    if (!videoId) {
      showError(labels.invalidUrl);
      return;
    }

    loading.style.display = 'block';
    fetchBtn.disabled = true;
    track('fetch_video', { page_path: location.pathname });

    try {
      const res = await fetch('/api/video?id=' + encodeURIComponent(videoId));
      const response = (await res.json()) as { success: boolean; message?: string; data?: VideoData };
      if (!response.success || !response.data) {
        showError(response.message || labels.networkError);
        return;
      }
      render(response.data);
    } catch {
      showError(labels.networkError);
    } finally {
      loading.style.display = 'none';
      fetchBtn.disabled = false;
    }
  }

  function render(data: VideoData) {
    $('vid-title').textContent = data.title;
    $('vid-author').textContent = data.author;
    $('vid-duration').textContent = formatDuration(data.lengthSeconds);
    const thumb = $<HTMLImageElement>('vid-thumb');
    thumb.src = data.thumbnailUrl;
    thumb.alt = data.title + ' thumbnail';
    $<HTMLAnchorElement>('vid-link').href = data.videoUrl;
    $('vid-desc').textContent = data.description.length > 200 ? data.description.slice(0, 200) + '...' : data.description;

    grid.innerHTML = '';
    if (!data.tracks.length) {
      grid.innerHTML = `<p style="color: var(--text-muted);">${escapeHtml(labels.noTracks)}</p>`;
    }
    for (const t of data.tracks) {
      const item = document.createElement('div');
      item.className = 'sub-item';
      item.innerHTML =
        '<div class="language-info">' +
          `<span class="language-name">${escapeHtml(t.language)}</span>` +
          `<span class="is-auto">${escapeHtml(t.isAutoGenerated ? labels.auto : labels.official)}</span>` +
        '</div>' +
        '<div class="download-options">' +
          '<button type="button" class="download-btn btn-srt" data-format="srt" title="Download SRT Subtitles">SRT</button>' +
          '<button type="button" class="download-btn btn-vtt" data-format="vtt" title="Download VTT Subtitles">VTT</button>' +
          '<button type="button" class="download-btn btn-txt" data-format="txt" title="Download Text Transcript">TXT</button>' +
          '<button type="button" class="download-btn btn-raw" data-format="raw" title="View Raw Text">RAW</button>' +
        '</div>';
      item.querySelectorAll<HTMLButtonElement>('button').forEach((btn) =>
        btn.addEventListener('click', () => downloadSub(btn, data, t, btn.dataset.format as Format)),
      );
      grid.appendChild(item);
    }
    result.style.display = 'block';
  }

  async function downloadSub(btn: HTMLButtonElement, data: VideoData, t: Track, format: Format) {
    const originalText = btn.innerText;
    btn.innerText = '...';
    btn.disabled = true;
    track('download_subtitle', { format, language: t.languageCode });

    // Open the RAW tab synchronously inside the click handler: a window.open() issued after an await
    // is treated as an unsolicited pop-up and blocked by most mobile browsers.
    let rawTab: Window | null = null;
    if (format === 'raw') {
      rawTab = window.open('', '_blank');
      rawTab?.document.write('<p style="font-family: sans-serif; padding: 20px;">Loading transcript…</p>');
    }

    try {
      const captions = await loadCaptions(t);
      if (!captions.length) throw new Error('empty');

      const ext = format === 'srt' ? '.srt' : format === 'vtt' ? '.vtt' : '.txt';
      const fileName = buildFileName(data.title, t.languageCode, t.isAutoGenerated, ext);
      const content = format === 'srt' ? captionsToSrt(captions) : format === 'vtt' ? captionsToVtt(captions) : captionsToTxt(captions);

      if (format === 'raw') {
        const html =
          '<!doctype html><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">' +
          `<title>Raw Transcript - ${escapeHtml(fileName)}</title>` +
          '<pre style="white-space: pre-wrap; font-family: monospace; padding: 20px; margin: 0; min-height: 100vh; background: #0f172a; color: #f8fafc;">' +
          escapeHtml(content) + '</pre>';
        if (rawTab && !rawTab.closed) {
          rawTab.document.open();
          rawTab.document.write(html);
          rawTab.document.close();
        } else {
          // Pop-up blocked: show the text in this tab instead.
          window.location.assign(URL.createObjectURL(new Blob([html], { type: 'text/html;charset=utf-8' })));
        }
      } else {
        const link = document.createElement('a');
        link.href = URL.createObjectURL(new Blob([content], { type: 'text/plain;charset=utf-8' }));
        link.download = fileName;
        document.body.appendChild(link);
        link.click();
        link.remove();
        setTimeout(() => URL.revokeObjectURL(link.href), 10000);
      }
    } catch {
      rawTab?.close();
      showError(labels.downloadError, true);
    } finally {
      btn.innerText = originalText;
      btn.disabled = false;
    }
  }

  fetchBtn.addEventListener('click', fetchVideo);
  input.addEventListener('keydown', (e) => {
    if (e.key === 'Enter') {
      e.preventDefault();
      fetchVideo();
    }
  });
}
